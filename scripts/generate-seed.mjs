// Generates supabase/seed.sql from the frontend's synthetic dataset so the
// database and the local demo never drift apart.
//
//   npm run db:seed:generate
//
// Requires Node >= 22.18 (built-in TypeScript type stripping).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  CUSTOMERS,
  DEMO_START_TIME,
  createSyntheticDataset,
} from "../src/lib/demo/synthetic-data.ts";

const out = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
const data = createSyntheticDataset();

const lit = (value) => {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return String(value);
  return `'${String(value).replaceAll("'", "''")}'`;
};
const arr = (values) => (values.length ? `array[${values.map(lit).join(", ")}]::text[]` : "'{}'::text[]");
const rows = (list, toRow) => list.map((item) => `  (${toRow(item).join(", ")})`).join(",\n");

const busy = data.drivers.flatMap((d) => d.busy.map((slot) => ({ driverId: d.id, ...slot })));

const sql = `-- LEGACY LOCAL-DEMO SEED — DO NOT LOAD INTO THE SHARED SUPABASE PROJECT.
-- The authoritative dataset is supabase/import/authoritative_dataset.sql
-- (see docs/dataset-import.md). This file mirrors the frontend's built-in
-- 20-job demo data and is kept only for local testing.
--
-- GENERATED by scripts/generate-seed.mjs from src/lib/demo/synthetic-data.ts.
-- Do not edit by hand; run \`npm run db:seed:generate\` instead.
-- SYNTHETIC DEMO DATA: every company, terminal, person and container is fictional.
--
-- Safe to re-run: clears operational tables, then inserts the original dataset.

begin;

truncate table
  public.driver_reports,
  public.recovery_plans,
  public.activity_events,
  public.driver_busy_slots,
  public.jobs,
  public.drivers,
  public.customers,
  public.terminals,
  public.demo_state
restart identity;

insert into public.demo_state (id, sim_now, inputs_version) values (1, ${lit(DEMO_START_TIME)}, 1);

insert into public.terminals (id, short_name, name, portal_status) values
${rows(data.terminals, (t) => [lit(t.id), lit(t.shortName), lit(t.name), lit(t.portalStatus)])};

insert into public.customers (id, name) values
${rows(CUSTOMERS, (c) => [lit(c.id), lit(c.name)])};

insert into public.drivers (id, name, equipment, availability, available_from, last_report, last_note) values
${rows(data.drivers, (d) => [lit(d.id), lit(d.name), arr(d.equipment), lit(d.availability), lit(d.availableFrom), lit(d.lastReport), lit(d.lastNote)])};

insert into public.jobs (
  id, container, customer_id, terminal_id, priority, deadline,
  appointment_status, appointment_start, appointment_end,
  container_available, holds, required_equipment
) values
${rows(data.jobs, (j) => [
  lit(j.id), lit(j.container), lit(j.customerId), lit(j.terminalId), lit(j.priority), lit(j.deadline),
  lit(j.appointment.status), lit(j.appointment.window?.start ?? null), lit(j.appointment.window?.end ?? null),
  lit(j.containerAvailable), arr(j.holds), lit(j.requiredEquipment),
])};
${busy.length ? `
insert into public.driver_busy_slots (driver_id, start_at, end_at, label, job_id) values
${rows(busy, (b) => [lit(b.driverId), lit(b.start), lit(b.end), lit(b.label), lit(b.jobId ?? null)])};
` : ""}
insert into public.activity_events (id, at, kind, severity, message) overriding system value values
${rows(data.events, (e) => [lit(e.id), lit(e.at), lit(e.kind), lit(e.severity), lit(e.message)])};

select setval(pg_get_serial_sequence('public.activity_events', 'id'), (select max(id) from public.activity_events));

commit;
`;

writeFileSync(out, sql);
console.log(`Wrote ${out}: ${data.jobs.length} jobs, ${data.drivers.length} drivers, ${CUSTOMERS.length} customers, ${data.terminals.length} terminals.`);
