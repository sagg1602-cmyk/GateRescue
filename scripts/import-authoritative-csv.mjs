// Generates the scenario import from the scenario owner's CSVs (data/source/,
// unchanged) plus the versioned scenario configuration
// (data/scenario/terminal-a-outage.v1.json):
//
//   npm run db:import:generate
//
// Output: supabase/import/authoritative_dataset.sql
//
// The mapping lives in src/lib/recovery/scenario-dataset.ts (shared with the
// tests). The import RESETS the scenario to its post-import state (after the
// 14:05 Terminal A scheduling outage): it clears driver reports, plans and
// activity, then inserts the dataset. It aborts without changes if the
// database holds rows from another dataset (e.g. the legacy 20-job seed).
// Driver reports (D02 at 14:10) are not imported; send them through the API.
//
// Requires Node >= 22.18 (built-in TypeScript type stripping).

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { assertScenarioConfig } from "../src/lib/recovery/scenario-config.ts";
import { buildScenarioDataset } from "../src/lib/recovery/scenario-dataset.ts";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");
const sha = (text) => createHash("sha256").update(text).digest("hex");
const outFile = fileURLToPath(new URL("supabase/import/authoritative_dataset.sql", root));

const configPath = "data/scenario/terminal-a-outage.v1.json";
const configText = read(configPath);
const config = JSON.parse(configText);
assertScenarioConfig(config);

const sources = {
  customers: "data/source/gaterescue_customers.csv",
  drivers: "data/source/gaterescue_drivers.csv",
  jobs: "data/source/gaterescue_jobs.csv",
};
const csv = Object.fromEntries(Object.entries(sources).map(([k, p]) => [k, read(p)]));
const dataset = buildScenarioDataset(csv, config);

/* -------------------------------------------------------------------- SQL */

const lit = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
  return `'${String(v).replaceAll("'", "''")}'`;
};

function insert(table, rows, extra = "") {
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")})${extra} values\n${values};`;
}

const ids = (list) => list.map(lit).join(", ");

const terminalRows = dataset.terminals.map((t) => ({
  id: t.id,
  short_name: t.shortName,
  name: t.name,
  portal_status: t.portalStatus,
  data_origin: config.dataOrigin,
}));

const customerRows = dataset.customers.map((c) => ({
  id: c.id,
  name: c.name,
  customer_type: c.customerType,
  contact_name: c.contactName,
  contact_phone: c.contactPhone,
  city: c.city,
  data_origin: c.dataOrigin,
}));

const driverRows = dataset.drivers.map(({ driver: d, source: s }) => ({
  id: d.id,
  name: d.name,
  phone: s.phone,
  equipment: d.equipment,
  source_equipment: s.sourceEquipment,
  availability: d.availability,
  source_status: s.sourceStatus,
  available_from: d.availableFrom,
  available_until: d.availableUntil ?? null,
  last_report: d.lastReport,
  last_note: d.lastNote,
  location: d.location ?? null,
  checked_in: s.checkedIn,
  data_origin: s.dataOrigin,
}));

const jobRows = dataset.jobs.map(({ job: j, source: s }) => ({
  id: j.id,
  container: j.container,
  customer_id: j.customerId,
  terminal_id: j.terminalId,
  source_terminal: s.sourceTerminal,
  priority: j.priority,
  criticality_tier: j.tier ?? null,
  criticality_basis: j.criticalityBasis ?? null,
  criticality_stated_by: j.criticalityStatedBy ?? null,
  deadline: j.deadline,
  appointment_status: j.appointment.status,
  appointment_start: j.appointment.window?.start ?? null,
  appointment_end: j.appointment.window?.end ?? null,
  pre_outage_status: j.appointment.preOutage?.status ?? null,
  pre_outage_start: j.appointment.preOutage?.window?.start ?? null,
  pre_outage_end: j.appointment.preOutage?.window?.end ?? null,
  container_available: j.containerAvailable,
  container_status_as_of: j.containerAvailabilityAsOf ?? null,
  holds: j.holds,
  required_equipment: j.requiredEquipment,
  source_container_type: s.sourceContainerType,
  cargo_description: j.cargoDescription ?? null,
  last_free_day: j.lastFreeDay ?? null,
  assigned_driver_id: j.originalAssignedDriverId ?? null,
  data_origin: s.dataOrigin,
}));

const eventRows = dataset.events.map((e, i) => ({
  id: i + 1,
  at: e.at,
  kind: e.kind,
  severity: e.severity,
  message: e.message,
  data_origin: config.dataOrigin,
}));

const sql = `-- GENERATED by scripts/import-authoritative-csv.mjs — do not edit by hand.
-- SYNTHETIC DEMO DATA. Sources (unchanged), sha256:
${[...Object.values(sources), configPath].map((p) => `--   ${p}  ${sha(read(p))}`).join("\n")}
--
-- Requires migrations 20261017000000, 20261019000000 and 20261019120000.
-- RESETS the scenario "${config.id}" v${config.version} to ${dataset.simNow}
-- (after the Terminal A scheduling outage): clears driver reports, plans,
-- activity and busy slots, then inserts the dataset. Aborts without changes
-- if rows from another dataset exist (e.g. the legacy 20-job seed).
-- D02's 14:10 report is NOT included: send it through POST /api/driver-reports.

begin;

do $$
declare
  foreign_rows text;
begin
  select string_agg(t || ':' || id, ', ') into foreign_rows from (
    select 'customers' t, id from public.customers where id not in (${ids(customerRows.map((r) => r.id))})
    union all select 'drivers', id from public.drivers where id not in (${ids(driverRows.map((r) => r.id))})
    union all select 'jobs', id from public.jobs where id not in (${ids(jobRows.map((r) => r.id))})
    union all select 'terminals', id from public.terminals where id not in (${ids(terminalRows.map((r) => r.id))})
  ) x;
  if foreign_rows is not null then
    raise exception 'Import aborted: database contains rows outside this dataset (%). Remove them first.', foreign_rows;
  end if;
end $$;

truncate table
  public.driver_reports,
  public.recovery_plans,
  public.activity_events,
  public.driver_busy_slots,
  public.jobs,
  public.drivers,
  public.customers,
  public.terminals,
  public.demo_state
restart identity;

insert into public.demo_state (id, sim_now, inputs_version, scenario_id, scenario_version, time_zone) values
  (1, ${lit(dataset.simNow)}, 1, ${lit(config.id)}, ${config.version}, ${lit(config.timeZone)});

${insert("terminals", terminalRows)}

${insert("customers", customerRows)}

${insert("drivers", driverRows)}

${insert("jobs", jobRows)}

${insert("activity_events", eventRows, " overriding system value")}
select setval(pg_get_serial_sequence('public.activity_events', 'id'), ${eventRows.length});

commit;
`;

mkdirSync(fileURLToPath(new URL("supabase/import/", root)), { recursive: true });
writeFileSync(outFile, sql);
console.log(
  `Wrote ${outFile}: scenario ${config.id} v${config.version} at ${dataset.simNow}; ` +
    `${terminalRows.length} terminals, ${customerRows.length} customers, ${driverRows.length} drivers, ${jobRows.length} jobs, ${eventRows.length} events.`,
);
