-- GateRescue operational schema (backend foundation).
--
-- Mirrors src/lib/shared/operational-types.ts. Simulated-day times use
-- `timestamp` (no time zone) so PostgREST returns them in the frontend's
-- IsoLocal format ("2026-10-17T07:30:00"). Real-world provenance instants use
-- `timestamptz`.
--
-- Security model: RLS is enabled on every table with NO policies, and all
-- privileges are revoked from anon/authenticated. Only the server-side secret
-- key (service_role) can read or write; the browser never talks to Supabase.

-- ------------------------------------------------------------------ tables

create table public.terminals (
  id text primary key check (id in ('term-a', 'term-b')),
  short_name text not null,
  name text not null,
  portal_status text not null default 'online'
    check (portal_status in ('online', 'outage', 'reconciling'))
);

create table public.customers (
  id text primary key,
  name text not null
);

create table public.drivers (
  id text primary key,
  name text not null,
  equipment text[] not null default '{}'
    check (equipment <@ array['chassis-40', 'chassis-20', 'reefer-40', 'triaxle']),
  availability text not null
    check (availability in ('available', 'on-job', 'off-duty', 'unreachable')),
  available_from timestamp not null,
  last_report timestamp not null,
  last_note text not null default ''
);

create table public.jobs (
  id text primary key,
  container text not null unique,
  customer_id text not null references public.customers (id),
  terminal_id text not null references public.terminals (id),
  priority text not null check (priority in ('critical', 'high', 'normal')),
  deadline timestamp not null,
  appointment_status text not null
    check (appointment_status in ('confirmed', 'unverified', 'none', 'lost')),
  appointment_start timestamp,
  appointment_end timestamp,
  pre_outage_status text
    check (pre_outage_status in ('confirmed', 'unverified', 'none', 'lost')),
  pre_outage_start timestamp,
  pre_outage_end timestamp,
  container_available boolean not null,
  holds text[] not null default '{}'
    check (holds <@ array['customs', 'freight', 'usda']),
  required_equipment text not null
    check (required_equipment in ('chassis-40', 'chassis-20', 'reefer-40', 'triaxle')),
  approval_driver_id text references public.drivers (id),
  approval_at timestamp,
  check ((appointment_start is null) = (appointment_end is null)),
  check ((approval_driver_id is null) = (approval_at is null))
);

create table public.driver_busy_slots (
  id bigint generated by default as identity primary key,
  driver_id text not null references public.drivers (id) on delete cascade,
  start_at timestamp not null,
  end_at timestamp not null,
  label text not null,
  job_id text references public.jobs (id) on delete set null,
  check (end_at > start_at)
);
create index driver_busy_slots_driver_idx on public.driver_busy_slots (driver_id);

create table public.activity_events (
  id bigint generated by default as identity primary key,
  at timestamp not null,
  kind text not null check (kind in ('system', 'terminal', 'driver', 'plan', 'dispatcher')),
  severity text not null check (severity in ('info', 'success', 'warning', 'critical')),
  message text not null
);
create index activity_events_at_idx on public.activity_events (at desc, id desc);

-- Singleton row holding the simulated clock and the operational input version.
create table public.demo_state (
  id smallint primary key default 1 check (id = 1),
  sim_now timestamp not null,
  inputs_version integer not null default 1
);

create table public.recovery_plans (
  id bigint generated by default as identity primary key,
  generated_at timestamp not null,
  inputs_version integer not null,
  status text not null check (status in ('current', 'invalidated')),
  invalidated_reason text,
  -- Array of Recommendation objects (see operational-types.ts).
  recommendations jsonb not null default '[]'::jsonb
);
-- At most one plan can be pending at a time.
create unique index recovery_plans_one_current on public.recovery_plans (status) where status = 'current';

create table public.driver_reports (
  id uuid primary key default gen_random_uuid(),
  driver_id text not null references public.drivers (id),
  source text not null check (source in ('dispatcher', 'retell')),
  provider_event_id text not null,
  reported_at timestamptz not null,
  received_at timestamptz not null default now(),
  applied_at timestamp,
  availability text not null
    check (availability in ('available', 'on-job', 'off-duty', 'unreachable')),
  available_from time not null,
  note text not null default '',
  -- Deduplicates retried deliveries (e.g. Retell webhooks) per source.
  unique (source, provider_event_id)
);
create index driver_reports_driver_idx on public.driver_reports (driver_id, received_at desc);

-- ---------------------------------------------------------- lock it down

alter table public.terminals enable row level security;
alter table public.customers enable row level security;
alter table public.drivers enable row level security;
alter table public.jobs enable row level security;
alter table public.driver_busy_slots enable row level security;
alter table public.activity_events enable row level security;
alter table public.demo_state enable row level security;
alter table public.recovery_plans enable row level security;
alter table public.driver_reports enable row level security;

revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

-- ------------------------------------------------- apply_driver_report()
--
-- Atomically: dedupe by (source, provider_event_id), store the report with
-- provenance, advance the simulated clock one minute, update the driver,
-- log the check-in, bump inputs_version, and invalidate any pending plan.
-- Mirrors the "driver-check-in" case in src/lib/demo/demo-state.ts.

create or replace function public.apply_driver_report(
  p_driver_id text,
  p_source text,
  p_provider_event_id text,
  p_reported_at timestamptz,
  p_availability text,
  p_available_from time,
  p_note text
) returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_driver_name text;
  v_report public.driver_reports;
  v_sim_now timestamp;
  v_inputs_version integer;
  v_note text := btrim(coalesce(p_note, ''));
  v_plan_id bigint;
  v_plan_recommendations jsonb;
  v_pending integer;
begin
  select name into v_driver_name from public.drivers where id = p_driver_id;
  if v_driver_name is null then
    raise exception 'driver_not_found' using errcode = 'P0002';
  end if;

  insert into public.driver_reports
    (driver_id, source, provider_event_id, reported_at, availability, available_from, note)
  values
    (p_driver_id, p_source, p_provider_event_id, p_reported_at, p_availability, p_available_from, v_note)
  on conflict (source, provider_event_id) do nothing
  returning * into v_report;

  if v_report.id is null then
    select * into v_report from public.driver_reports
    where source = p_source and provider_event_id = p_provider_event_id;
    select inputs_version into v_inputs_version from public.demo_state where id = 1;
    return jsonb_build_object(
      'duplicate', true,
      'report', to_jsonb(v_report),
      'inputs_version', v_inputs_version,
      'plan_invalidated', false
    );
  end if;

  update public.demo_state
     set sim_now = sim_now + interval '1 minute',
         inputs_version = inputs_version + 1
   where id = 1
  returning sim_now, inputs_version into v_sim_now, v_inputs_version;
  if v_sim_now is null then
    raise exception 'demo_state row missing — run the seed' using errcode = 'P0001';
  end if;

  update public.drivers
     set availability = p_availability,
         available_from = date_trunc('day', v_sim_now) + p_available_from,
         last_report = v_sim_now,
         last_note = case when v_note = '' then last_note else v_note end
   where id = p_driver_id;

  update public.driver_reports set applied_at = v_sim_now where id = v_report.id
  returning * into v_report;

  insert into public.activity_events (at, kind, severity, message)
  values (
    v_sim_now,
    'driver',
    case when p_availability = 'available' then 'success' else 'info' end,
    format('%s checked in: %s, free from %s.%s%s',
      v_driver_name,
      replace(p_availability, '-', ' '),
      to_char(p_available_from, 'HH24:MI'),
      case when v_note = '' then '' else format(' “%s”', v_note) end,
      case when p_source = 'dispatcher' then '' else format(' (via %s)', p_source) end)
  );

  update public.recovery_plans
     set status = 'invalidated',
         invalidated_reason = v_driver_name || ' check-in'
   where status = 'current'
  returning id, recommendations into v_plan_id, v_plan_recommendations;

  if v_plan_id is not null then
    select count(*) into v_pending
      from jsonb_array_elements(v_plan_recommendations) r
     where not coalesce((r ->> 'approved')::boolean, false)
       and r ->> 'category' <> 'blocked';
    insert into public.activity_events (at, kind, severity, message)
    values (
      v_sim_now, 'plan', 'warning',
      format('Pending recommendations invalidated (%s unapproved): %s check-in. Regenerate the plan.',
        v_pending, v_driver_name)
    );
  end if;

  return jsonb_build_object(
    'duplicate', false,
    'report', to_jsonb(v_report),
    'inputs_version', v_inputs_version,
    'plan_invalidated', v_plan_id is not null
  );
end;
$$;

revoke all on function public.apply_driver_report(text, text, text, timestamptz, text, time, text)
  from public, anon, authenticated;
grant execute on function public.apply_driver_report(text, text, text, timestamptz, text, time, text)
  to service_role;
